"""Database backends for USIPHU's learner and faculty repositories."""
from __future__ import annotations

import os
import re
import sqlite3
from pathlib import Path
from typing import Any, Protocol, runtime_checkable

DEFAULT_SQLITE_PATH = Path(os.getenv("USIPHU_DB_PATH", "usiphu_data.sqlite3"))


@runtime_checkable
class DatabaseBackend(Protocol):
    def connect(self, path: Path | None = None) -> Any: ...


class SQLiteBackend:
    """SQLite implementation preserving local development and test behavior."""

    def __init__(self, default_path: Path | None = None) -> None:
        self.default_path = default_path or Path(
            os.getenv("USIPHU_DB_PATH", str(DEFAULT_SQLITE_PATH))
        )

    def connect(self, path: Path | None = None) -> sqlite3.Connection:
        database_path = path or self.default_path
        database_path.parent.mkdir(parents=True, exist_ok=True)
        connection = sqlite3.connect(database_path)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys=ON")
        return connection


class HybridRow(dict):
    """Mapping row that also preserves SQLite-style integer column access."""

    def __init__(self, names: list[str], values: tuple[Any, ...]) -> None:
        super().__init__(zip(names, values))
        self._values = values

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _hybrid_row_factory(cursor: Any) -> Any:
    names = [column.name for column in cursor.description]
    return lambda values: HybridRow(names, values)


class PostgresConnection:
    """Small DB-API compatibility wrapper for SQL used by current repositories."""

    is_postgres = True

    def __init__(self, connection: Any) -> None:
        self._connection = connection

    @staticmethod
    def _sql(statement: str) -> str:
        statement = re.sub(
            r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            statement,
            flags=re.IGNORECASE,
        )
        # Repository statements use qmark placeholders; psycopg uses %s.
        statement = re.sub(r"(?<!:):([A-Za-z_][A-Za-z0-9_]*)", r"%(\\1)s", statement)
        return statement.replace("?", "%s")

    def execute(self, statement: str, parameters: Any = None) -> Any:
        sql = self._sql(statement)
        if parameters is None:
            return self._connection.execute(sql)
        return self._connection.execute(sql, parameters)

    def executescript(self, script: str) -> None:
        # The schema scripts in this project contain plain DDL statements only.
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def __enter__(self) -> "PostgresConnection":
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> Any:
        return self._connection.__exit__(exc_type, exc, traceback)


class PostgresBackend:
    """PostgreSQL driver for Supabase or another managed PostgreSQL service."""

    def __init__(self, database_url: str | None = None) -> None:
        self.database_url = database_url or os.getenv("SUPABASE_DB_URL") or os.getenv(
            "DATABASE_URL"
        )
        if not self.database_url:
            raise RuntimeError(
                "PostgreSQL requires SUPABASE_DB_URL or DATABASE_URL. "
                "Set it in the hosting provider's secret manager."
            )

    def connect(self, path: Path | None = None) -> PostgresConnection:
        if path is not None:
            raise ValueError("A filesystem database path cannot be used with PostgreSQL.")
        try:
            import psycopg
        except ImportError as exc:
            raise RuntimeError(
                "PostgreSQL support requires the pinned psycopg[binary] dependency."
            ) from exc
        connection = psycopg.connect(
            self.database_url,
            sslmode="require",
            row_factory=_hybrid_row_factory,
            prepare_threshold=None,
            application_name="usiphu",
        )
        return PostgresConnection(connection)


def get_database_backend() -> DatabaseBackend:
    """Select the configured backend; never silently fall back to SQLite."""
    backend_name = os.getenv("USIPHU_DATABASE_BACKEND", "sqlite").strip().lower()
    if backend_name == "sqlite":
        return SQLiteBackend()
    if backend_name in {"postgres", "postgresql"}:
        return PostgresBackend()
    raise RuntimeError(
        f"Unsupported USIPHU_DATABASE_BACKEND={backend_name!r}; "
        "choose 'sqlite' or 'postgres'."
    )


def connect_database(path: Path | None = None) -> Any:
    """Open a connection through the selected backend."""
    backend = get_database_backend()
    if isinstance(backend, PostgresBackend):
        return backend.connect()
    return backend.connect(path=path)
