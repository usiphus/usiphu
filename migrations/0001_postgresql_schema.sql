-- USIPHU initial PostgreSQL schema (13 persistence tables).
-- Apply once to a fresh private PostgreSQL database.
CREATE TABLE IF NOT EXISTS flashcards (
  id TEXT PRIMARY KEY, owner_id TEXT NOT NULL DEFAULT 'local',
  specialty_id TEXT NOT NULL, topic_id TEXT NOT NULL,
  prompt TEXT NOT NULL, answer TEXT NOT NULL, source_url TEXT
);
CREATE INDEX IF NOT EXISTS idx_flashcards_owner ON flashcards(owner_id);
CREATE TABLE IF NOT EXISTS generated_drafts (
  id TEXT PRIMARY KEY, owner_id TEXT NOT NULL,
  specialty_id TEXT NOT NULL, topic_id TEXT NOT NULL,
  payload_json TEXT NOT NULL, review_status TEXT NOT NULL DEFAULT 'draft'
    CHECK(review_status='draft'),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_generated_drafts_owner ON generated_drafts(owner_id, created_at);
CREATE TABLE IF NOT EXISTS review_states (
  card_id TEXT PRIMARY KEY REFERENCES flashcards(id) ON DELETE CASCADE,
  repetitions INTEGER NOT NULL DEFAULT 0, interval_days INTEGER NOT NULL DEFAULT 0,
  ease_factor DOUBLE PRECISION NOT NULL DEFAULT 2.5, due_date TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS review_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, card_id TEXT NOT NULL,
  grade INTEGER NOT NULL CHECK(grade BETWEEN 0 AND 5),
  reviewed_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, next_due TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS question_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id TEXT NOT NULL,
  question_id TEXT NOT NULL, selected_option_id TEXT NOT NULL,
  is_correct INTEGER NOT NULL CHECK(is_correct IN (0,1)),
  session_id TEXT, elapsed_seconds INTEGER,
  attempted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_question_attempts_owner ON question_attempts(owner_id, attempted_at);
CREATE TABLE IF NOT EXISTS topic_progress (
  topic_id TEXT PRIMARY KEY, status TEXT NOT NULL DEFAULT 'not_started',
  confidence INTEGER NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 5),
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS learner_topic_progress (
  owner_id TEXT NOT NULL, topic_id TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'not_started',
  confidence INTEGER NOT NULL DEFAULT 0 CHECK(confidence BETWEEN 0 AND 5),
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(owner_id, topic_id)
);
CREATE TABLE IF NOT EXISTS faculty_question_reviews (
  question_id TEXT PRIMARY KEY,
  clinical_status TEXT NOT NULL DEFAULT 'pending'
    CHECK(clinical_status IN ('pending','approved','request_changes','rejected')),
  clinical_reviewer_id TEXT, clinical_reviewer_name TEXT, clinical_comment TEXT,
  clinical_reviewed_at TEXT,
  exam_status TEXT NOT NULL DEFAULT 'pending'
    CHECK(exam_status IN ('pending','approved','request_changes','rejected')),
  exam_reviewer_id TEXT, exam_reviewer_name TEXT, exam_comment TEXT,
  exam_reviewed_at TEXT, content_snapshot_json TEXT, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS faculty_question_review_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id TEXT NOT NULL,
  stage TEXT NOT NULL CHECK(stage IN ('clinical','exam')),
  decision TEXT NOT NULL CHECK(decision IN ('approve','request_changes','reject')),
  reviewer_id TEXT NOT NULL, reviewer_name TEXT NOT NULL, comment TEXT NOT NULL,
  content_snapshot_json TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_faculty_review_events_question
  ON faculty_question_review_events(question_id, id);
CREATE TABLE IF NOT EXISTS faculty_reviewer_roles (
  reviewer_id TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('admin','clinical_reviewer','exam_reviewer')),
  granted_by TEXT NOT NULL, granted_at TEXT NOT NULL,
  PRIMARY KEY(reviewer_id, role)
);
CREATE TABLE IF NOT EXISTS faculty_role_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reviewer_id TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('clinical_reviewer','exam_reviewer')),
  action TEXT NOT NULL CHECK(action IN ('grant','revoke')),
  actor_id TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_faculty_role_events_reviewer
  ON faculty_role_events(reviewer_id, id);
CREATE TABLE IF NOT EXISTS shared_assessment_reviews (
  item_id TEXT PRIMARY KEY, item_type TEXT NOT NULL, payload_json TEXT NOT NULL,
  content_hash TEXT NOT NULL, clinical_status TEXT NOT NULL DEFAULT 'pending',
  clinical_reviewer_id TEXT, clinical_reviewer_name TEXT, clinical_comment TEXT,
  exam_status TEXT NOT NULL DEFAULT 'pending', exam_reviewer_id TEXT,
  exam_reviewer_name TEXT, exam_comment TEXT, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS shared_assessment_review_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id TEXT NOT NULL,
  stage TEXT NOT NULL CHECK(stage IN ('clinical','exam')),
  decision TEXT NOT NULL CHECK(decision IN ('approve','request_changes','reject')),
  reviewer_id TEXT NOT NULL, reviewer_name TEXT NOT NULL, comment TEXT NOT NULL,
  content_snapshot_json TEXT NOT NULL, attestations_json TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_shared_assessment_events_item
  ON shared_assessment_review_events(item_id, id);
