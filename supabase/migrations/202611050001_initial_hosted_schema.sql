-- Initial hosted schema for USIPHU. Apply with Supabase CLI before enabling Postgres mode.
-- Application connections use a server-side PostgreSQL credential; browser users never connect directly.

CREATE TABLE IF NOT EXISTS public.flashcards (
  id text PRIMARY KEY, owner_id text NOT NULL DEFAULT 'local',
  specialty_id text NOT NULL, topic_id text NOT NULL,
  prompt text NOT NULL, answer text NOT NULL, source_url text
);
CREATE INDEX IF NOT EXISTS idx_flashcards_owner ON public.flashcards(owner_id);

CREATE TABLE IF NOT EXISTS public.generated_drafts (
  id text PRIMARY KEY, owner_id text NOT NULL, specialty_id text NOT NULL, topic_id text NOT NULL,
  payload_json text NOT NULL, review_status text NOT NULL DEFAULT 'draft' CHECK (review_status = 'draft'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_generated_drafts_owner ON public.generated_drafts(owner_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.review_states (
  card_id text PRIMARY KEY REFERENCES public.flashcards(id) ON DELETE CASCADE,
  repetitions integer NOT NULL DEFAULT 0, interval_days integer NOT NULL DEFAULT 0,
  ease_factor double precision NOT NULL DEFAULT 2.5, due_date date NOT NULL
);
CREATE TABLE IF NOT EXISTS public.review_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, card_id text NOT NULL,
  grade integer NOT NULL CHECK (grade BETWEEN 0 AND 5),
  reviewed_at timestamptz NOT NULL DEFAULT now(), next_due date NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_review_events_card ON public.review_events(card_id, id);

CREATE TABLE IF NOT EXISTS public.question_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id text NOT NULL,
  question_id text NOT NULL, selected_option_id text NOT NULL,
  is_correct integer NOT NULL CHECK (is_correct IN (0,1)),
  session_id text, elapsed_seconds integer CHECK (elapsed_seconds IS NULL OR elapsed_seconds >= 0),
  attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_question_attempts_owner ON public.question_attempts(owner_id, attempted_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.topic_progress (
  topic_id text PRIMARY KEY, status text NOT NULL DEFAULT 'not_started',
  confidence integer NOT NULL DEFAULT 0 CHECK (confidence BETWEEN 0 AND 5),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.learner_topic_progress (
  owner_id text NOT NULL, topic_id text NOT NULL, status text NOT NULL DEFAULT 'not_started',
  confidence integer NOT NULL DEFAULT 0 CHECK (confidence BETWEEN 0 AND 5),
  updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(owner_id, topic_id)
);
CREATE INDEX IF NOT EXISTS idx_learner_topic_progress_owner ON public.learner_topic_progress(owner_id, topic_id);

CREATE TABLE IF NOT EXISTS public.faculty_question_reviews (
  question_id text PRIMARY KEY,
  clinical_status text NOT NULL DEFAULT 'pending' CHECK (clinical_status IN ('pending','approved','request_changes','rejected')),
  clinical_reviewer_id text, clinical_reviewer_name text, clinical_comment text, clinical_reviewed_at text,
  exam_status text NOT NULL DEFAULT 'pending' CHECK (exam_status IN ('pending','approved','request_changes','rejected')),
  exam_reviewer_id text, exam_reviewer_name text, exam_comment text, exam_reviewed_at text,
  content_snapshot_json text, updated_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.faculty_question_review_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, question_id text NOT NULL,
  stage text NOT NULL CHECK (stage IN ('clinical','exam')),
  decision text NOT NULL CHECK (decision IN ('approve','request_changes','reject')),
  reviewer_id text NOT NULL, reviewer_name text NOT NULL, comment text NOT NULL,
  content_snapshot_json text NOT NULL, created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_faculty_review_events_question ON public.faculty_question_review_events(question_id, id);
CREATE TABLE IF NOT EXISTS public.faculty_reviewer_roles (
  reviewer_id text NOT NULL, role text NOT NULL CHECK (role IN ('admin','clinical_reviewer','exam_reviewer')),
  granted_by text NOT NULL, granted_at text NOT NULL, PRIMARY KEY(reviewer_id, role)
);
CREATE TABLE IF NOT EXISTS public.faculty_role_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reviewer_id text NOT NULL,
  role text NOT NULL CHECK (role IN ('clinical_reviewer','exam_reviewer')),
  action text NOT NULL CHECK (action IN ('grant','revoke')), actor_id text NOT NULL, created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_faculty_role_events_reviewer ON public.faculty_role_events(reviewer_id, id);

CREATE TABLE IF NOT EXISTS public.shared_assessment_reviews (
  item_id text PRIMARY KEY, item_type text NOT NULL, payload_json text NOT NULL, content_hash text NOT NULL,
  clinical_status text NOT NULL DEFAULT 'pending', clinical_reviewer_id text, clinical_reviewer_name text, clinical_comment text,
  exam_status text NOT NULL DEFAULT 'pending', exam_reviewer_id text, exam_reviewer_name text, exam_comment text,
  updated_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_shared_assessment_status ON public.shared_assessment_reviews(clinical_status, exam_status, updated_at DESC);
CREATE TABLE IF NOT EXISTS public.shared_assessment_review_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id text NOT NULL,
  stage text NOT NULL CHECK (stage IN ('clinical','exam')),
  decision text NOT NULL CHECK (decision IN ('approve','request_changes','reject')),
  reviewer_id text NOT NULL, reviewer_name text NOT NULL, comment text NOT NULL,
  content_snapshot_json text NOT NULL, attestations_json text NOT NULL, created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_shared_assessment_events_item ON public.shared_assessment_review_events(item_id, id);

-- Source file bytes live in a private Storage bucket; metadata and extraction JSON live in Postgres.
CREATE TABLE IF NOT EXISTS public.source_documents (
  source_id text PRIMARY KEY, sha256 text NOT NULL UNIQUE, object_key text NOT NULL UNIQUE,
  metadata_json text NOT NULL, uploaded_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_source_documents_uploaded ON public.source_documents(uploaded_at DESC);
CREATE TABLE IF NOT EXISTS public.source_extractions (
  source_id text PRIMARY KEY REFERENCES public.source_documents(source_id) ON DELETE CASCADE,
  payload_json text NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);

-- These JSON rows replace runtime writes to repository-local question-bank files on hosted deployments.
CREATE TABLE IF NOT EXISTS public.approved_question_bank (
  question_id text PRIMARY KEY, payload_json text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.approved_assessment_bank (
  assessment_id text PRIMARY KEY, payload_json text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);

-- RLS is enabled as defense in depth. Browser roles receive no table privileges or policies.
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY[
    'flashcards','generated_drafts','review_states','review_events','question_attempts',
    'topic_progress','learner_topic_progress','faculty_question_reviews',
    'faculty_question_review_events','faculty_reviewer_roles','faculty_role_events',
    'shared_assessment_reviews','shared_assessment_review_events','source_documents',
    'source_extractions','approved_question_bank','approved_assessment_bank'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', t);
    EXECUTE format('GRANT ALL ON TABLE public.%I TO postgres, service_role', t);
  END LOOP;
END $$;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO postgres, service_role;

